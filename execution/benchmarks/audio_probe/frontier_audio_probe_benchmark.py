def build_probe_audio():
    inline_b64 = os.environ.get("FRONTIER_AUDIO_FIXTURE_B64", "").strip()
    if inline_b64:
        return audios.from_base64(inline_b64, format="mp3")
    return audios.from_base64(SPEECH_MP3_B64.replace("\n", "").strip(), format="mp3")


@kbench.task(
    name="frontier_audio_probe_benchmark",
    description="PR-121-style audio transcription smoke test using an embedded speech fixture.",
)
def frontier_audio_probe_benchmark(llm) -> dict:
    response = llm.prompt("Transcribe this audio exactly.", audio=build_probe_audio())
    transcript = response.strip()
    kbench.assertions.assert_contains_regex(
        SPEECH_TRANSCRIPTION_PATTERN,
        transcript,
        expectation="LLM should transcribe the embedded speech fixture.",
    )
    return {
        "model_name": getattr(llm, "name", None) or getattr(llm, "model", None) or type(llm).__name__,
        "transcript": transcript,
        "pr121_supported_models": list(SUPPORTED_AUDIO_MODELS_FROM_PR121),
    }


if __name__ == "__main__":
    frontier_audio_probe_benchmark.run(kbench.llm)
